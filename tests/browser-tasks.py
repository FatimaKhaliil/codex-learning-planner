"""UI component integration against an explicit in-memory fixture, not a Firestore test."""
import asyncio, json
from pathlib import Path
from playwright.async_api import async_playwright, expect

async def main():
  out = Path('work/aufgabe-03'); out.mkdir(parents=True, exist_ok=True)
  checks = []
  async with async_playwright() as p:
    browser = await p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox','--disable-dev-shm-usage'])
    page = await browser.new_page(viewport={'width':1440,'height':1000})
    errors = []; page.on('pageerror', lambda error: errors.append(str(error)))
    await page.goto('http://127.0.0.1:5175/tests/fixtures/tasks.html')
    await expect(page.get_by_text('Noch keine Aufgaben', exact=True)).to_be_visible()
    await page.get_by_role('button', name='Aufgabe hinzufügen').click()
    await page.get_by_role('button', name='Eintrag hinzufügen').click()
    await expect(page.locator('#task-title-error')).to_be_visible()
    await expect(page.locator('#task-dueDate-error')).to_be_visible()
    await expect(page.locator('#task-title')).to_be_focused()
    checks.append('required fields and focus')
    await page.locator('#task-title').fill('Mathe lernen')
    await page.locator('#task-dueDate').fill('2026-11-01')
    await page.locator('#task-description').fill('Kapitel 3\nÜbungen')
    await page.locator('#task-subject').fill('Mathematik')
    await expect(page.locator('#task-status')).to_have_value('open')
    await page.get_by_role('button', name='Eintrag hinzufügen').click()
    await expect(page.get_by_role('button', name='Wird gespeichert')).to_be_disabled()
    await expect(page.get_by_role('heading', name='Mathe lernen', exact=True)).to_be_visible()
    checks.append('create, default status and loading state')
    await page.locator('.task-status').select_option('in-progress')
    await expect(page.locator('.notice.success')).to_have_text('Status gespeichert.')
    await expect(page.locator('.task-status')).to_have_value('in-progress')
    await page.locator('.task-status').select_option('done')
    await expect(page.locator('.task-status')).to_have_value('done')
    checks.append('both status transitions')
    await page.get_by_role('button', name='Mathe lernen bearbeiten', exact=True).click()
    await expect(page.locator('#task-title')).to_have_value('Mathe lernen')
    await expect(page.locator('#task-description')).to_have_value('Kapitel 3\nÜbungen')
    await page.locator('#task-title').fill('Analysis lernen')
    await page.locator('#task-subject').fill('')
    await page.get_by_role('button', name='Testfehler umschalten').click()
    await page.get_by_role('button', name='Änderungen speichern').click()
    await expect(page.get_by_role('alert')).to_contain_text('Internetverbindung')
    await expect(page.locator('#task-title')).to_have_value('Analysis lernen')
    await page.get_by_role('button', name='Testfehler umschalten').click()
    await page.get_by_role('button', name='Änderungen speichern').click()
    await expect(page.get_by_role('heading', name='Analysis lernen', exact=True)).to_be_visible()
    checks.append('edit, optional field removal, failed save preserves input and retry')
    await page.screenshot(path=str(out/'tasks-desktop.png'), full_page=True)
    for width in [390,320]:
      await page.set_viewport_size({'width':width,'height':844})
      assert await page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
      await page.screenshot(path=str(out/f'tasks-{width}.png'), full_page=True)
    checks.append('responsive cards at 390 and 320 without overflow')
    await page.get_by_role('button', name='Analysis lernen löschen', exact=True).click()
    await expect(page.get_by_role('dialog')).to_be_visible()
    await expect(page.get_by_role('button', name='Abbrechen')).to_be_focused()
    await page.keyboard.press('Escape')
    await expect(page.get_by_role('dialog')).to_have_count(0)
    await page.get_by_role('button', name='Analysis lernen löschen', exact=True).click()
    await page.get_by_role('button', name='Testfehler umschalten').evaluate('(button) => button.click()')
    await page.get_by_role('button', name='Endgültig löschen').click()
    await expect(page.get_by_role('dialog').get_by_role('alert')).to_contain_text('Internetverbindung')
    await page.get_by_role('button', name='Testfehler umschalten').evaluate('(button) => button.click()')
    await page.get_by_role('button', name='Endgültig löschen').click()
    await expect(page.get_by_text('Noch keine Aufgaben', exact=True)).to_be_visible()
    checks.append('modal focus, Escape cancellation, delete failure and retry')
    assert errors == [], errors
    await browser.close()
  print(json.dumps({'fixture':'in-memory component integration, NOT emulator', 'passed':checks}, indent=2))

asyncio.run(main())
